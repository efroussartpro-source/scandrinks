// Largeur et hauteur d'un JPEG, lues dans son segment SOF0 ou SOF2.
export function jpegSize(buffer) {
  let offset = 2
  while (offset < buffer.length) {
    const marker = buffer[offset + 1]
    const length = buffer.readUInt16BE(offset + 2)
    if (marker === 0xc0 || marker === 0xc2) {
      return { width: buffer.readUInt16BE(offset + 7), height: buffer.readUInt16BE(offset + 5) }
    }
    offset += 2 + length
  }
  throw new Error('JPEG sans segment SOF0 ni SOF2')
}

// Ajoute, juste après SOI, un segment APP1 Exif avec une seule entrée : Orientation (0x0112).
// Comme une photo d'iPhone prise en portrait (orientation 6) : les pixels sont couchés.
export function withExifOrientation(jpeg, orientation) {
  const tiff = Buffer.alloc(26)
  tiff.write('II', 0, 'latin1')
  tiff.writeUInt16LE(42, 2)
  tiff.writeUInt32LE(8, 4)
  tiff.writeUInt16LE(1, 8)
  tiff.writeUInt16LE(0x0112, 10)
  tiff.writeUInt16LE(3, 12)
  tiff.writeUInt32LE(1, 14)
  tiff.writeUInt16LE(orientation, 18)
  tiff.writeUInt32LE(0, 22)
  const payload = Buffer.concat([Buffer.from('Exif\0\0', 'latin1'), tiff])
  const header = Buffer.alloc(4)
  header.writeUInt16BE(0xffe1, 0)
  header.writeUInt16BE(payload.length + 2, 2)
  return Buffer.concat([jpeg.subarray(0, 2), header, payload, jpeg.subarray(2)])
}
